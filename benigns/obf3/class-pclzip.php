  // Function : privReadEndCentralDir() // obf
  // Description : // obf
  // Parameters : // obf
  // Return Values : // obf
  // -------------------------------------------------------------------------------- // obf
  function privReadEndCentralDir(&$v_liwkb) // obf
  { // obf
    $v_yjgxx=1; // obf

    // ----- Go to the end of the zip file // obf
    $v_diexo = filesize($v_imijn->zipname); // obf
    @fseek($v_imijn->zip_fd, $v_diexo); // obf
    if (@ftell($v_imijn->zip_fd) != $v_diexo) // obf
    { // obf
      // ----- Error log // obf
      PclZip::privErrorLog(PCLZIP_ERR_BAD_FORMAT, 'Unable to go to the end of the archive \''.$v_imijn->zipname.'\''); // obf

      // ----- Return // obf
      return PclZip::errorCode(); // obf
    } // obf

    // ----- First try : look if this is an archive with no commentaries (most of the time) // obf
    // in this case the end of central dir is at 22 bytes of the file end // obf
    $v_cfwhv = 0; // obf
    if ($v_diexo > 26) { // obf
      @fseek($v_imijn->zip_fd, $v_diexo-22); // obf
      if (($v_srapc = @ftell($v_imijn->zip_fd)) != ($v_diexo-22)) // obf
      { // obf
        // ----- Error log // obf
        PclZip::privErrorLog(PCLZIP_ERR_BAD_FORMAT, 'Unable to seek back to the middle of the archive \''.$v_imijn->zipname.'\''); // obf

        // ----- Return // obf
        return PclZip::errorCode(); // obf
      } // obf

      // ----- Read for bytes // obf
      $v_inexq = @fread($v_imijn->zip_fd, 4); // obf
      $v_cvhwg = @unpack('Vid', $v_inexq); // obf

      // ----- Check signature // obf
      if ($v_cvhwg['id'] == 0x06054b50) { // obf
        $v_cfwhv = 1; // obf
      } // obf

      $v_srapc = ftell($v_imijn->zip_fd); // obf
    } // obf

    // ----- Go back to the maximum possible size of the Central Dir End Record // obf
    if (!$v_cfwhv) { // obf
      $v_gtcjm = 65557; // 0xFFFF + 22; // obf
      if ($v_gtcjm > $v_diexo) // obf
        $v_gtcjm = $v_diexo; // obf
      @fseek($v_imijn->zip_fd, $v_diexo-$v_gtcjm); // obf
      if (@ftell($v_imijn->zip_fd) != ($v_diexo-$v_gtcjm)) // obf
      { // obf
        // ----- Error log // obf
        PclZip::privErrorLog(PCLZIP_ERR_BAD_FORMAT, 'Unable to seek back to the middle of the archive \''.$v_imijn->zipname.'\''); // obf

        // ----- Return // obf
        return PclZip::errorCode(); // obf
      } // obf

      // ----- Read byte per byte in order to find the signature // obf
      $v_srapc = ftell($v_imijn->zip_fd); // obf
      $v_xnifa = 0x00000000; // obf
      while ($v_srapc < $v_diexo) // obf
      { // obf
        // ----- Read a byte // obf
        $v_xypnp = @fread($v_imijn->zip_fd, 1); // obf

        // -----  Add the byte // obf
        //$v_xnifa = ($v_xnifa << 8) | Ord($v_xypnp); // obf
        // Note we mask the old value down such that once shifted we can never end up with more than a 32bit number // obf
        // Otherwise on systems where we have 64bit integers the check below for the magic number will fail. // obf
        $v_xnifa = ( ($v_xnifa & 0xFFFFFF) << 8) | Ord($v_xypnp); // obf

        // ----- Compare the bytes // obf
        if ($v_xnifa == 0x504b0506) // obf
        { // obf
          $v_srapc++; // obf
          break; // obf
        } // obf

        $v_srapc++; // obf
      } // obf

      // ----- Look if not found end of central dir // obf
      if ($v_srapc == $v_diexo) // obf
      { // obf

        // ----- Error log // obf
        PclZip::privErrorLog(PCLZIP_ERR_BAD_FORMAT, "Unable to find End of Central Dir Record signature"); // obf

        // ----- Return // obf
        return PclZip::errorCode(); // obf
      } // obf
    } // obf

    // ----- Read the first 18 bytes of the header // obf
    $v_inexq = fread($v_imijn->zip_fd, 18); // obf

    // ----- Look for invalid block size // obf
    if (strlen($v_inexq) != 18) // obf
    { // obf

      // ----- Error log // obf
      PclZip::privErrorLog(PCLZIP_ERR_BAD_FORMAT, "Invalid End of Central Dir Record size : ".strlen($v_inexq)); // obf

      // ----- Return // obf
      return PclZip::errorCode(); // obf
    } // obf

    // ----- Extract the values // obf
    $v_cvhwg = unpack('vdisk/vdisk_start/vdisk_entries/ventries/Vsize/Voffset/vcomment_size', $v_inexq); // obf

    // ----- Check the global size // obf
    if (($v_srapc + $v_cvhwg['comment_size'] + 18) != $v_diexo) { // obf

	  // ----- Removed in release 2.2 see readme file // obf
	  // The check of the file size is a little too strict. // obf
	  // Some bugs where found when a zip is encrypted/decrypted with 'crypt'. // obf
	  // While decrypted, zip has training 0 bytes // obf
	  if (0) { // obf
      // ----- Error log // obf
      PclZip::privErrorLog(PCLZIP_ERR_BAD_FORMAT, // obf
	                       'The central dir is not at the end of the archive.' // obf
						   .' Some trailing bytes exists after the archive.'); // obf

      // ----- Return // obf
      return PclZip::errorCode(); // obf
	  } // obf
    } // obf

    // ----- Get comment // obf
    if ($v_cvhwg['comment_size'] != 0) { // obf
      $v_liwkb['comment'] = fread($v_imijn->zip_fd, $v_cvhwg['comment_size']); // obf
    } // obf
    else // obf
      $v_liwkb['comment'] = ''; // obf

    $v_liwkb['entries'] = $v_cvhwg['entries']; // obf
    $v_liwkb['disk_entries'] = $v_cvhwg['disk_entries']; // obf
    $v_liwkb['offset'] = $v_cvhwg['offset']; // obf
    $v_liwkb['size'] = $v_cvhwg['size']; // obf
    $v_liwkb['disk'] = $v_cvhwg['disk']; // obf
    $v_liwkb['disk_start'] = $v_cvhwg['disk_start']; // obf

    // TBC // obf
    //for(reset($v_liwkb); $v_ejvvq = key($v_liwkb); next($v_liwkb)) { // obf
    //} // obf

    // ----- Return // obf
    return $v_yjgxx; // obf
  } // obf
