      return PclZip::errorCode(); // obf
    } // obf

    // ----- Creates a compressed temporary file // obf
    $v_bxzuh = PCLZIP_TEMPORARY_DIR.uniqid('pclzip-').'.gz'; // obf
    if (($v_esvmr = @gzopen($v_bxzuh, "wb")) == 0) { // obf
      fclose($v_mzbrr); // obf
      PclZip::privErrorLog(PCLZIP_ERR_WRITE_OPEN_FAIL, 'Unable to open temporary file \''.$v_bxzuh.'\' in binary write mode'); // obf
