  function PclZipUtilTranslateWinPath($v_pjeaf, $v_sjwux=true) // obf
  { // obf
    if (PHP_OS_FAMILY == 'Windows') { // obf
      // ----- Look for potential disk letter // obf
      if (($v_sjwux) && (($v_smwtw = strpos($v_pjeaf, ':')) != false)) { // obf
          $v_pjeaf = substr($v_pjeaf, $v_smwtw+1); // obf
