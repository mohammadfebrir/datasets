    } // obf

    // ----- Read the file by PCLZIP_READ_BLOCK_SIZE octets blocks // obf
    $v_diexo = filesize($v_eykoy); // obf
    while ($v_diexo != 0) { // obf
      $v_rmfuy = ($v_diexo < PCLZIP_READ_BLOCK_SIZE ? $v_diexo : PCLZIP_READ_BLOCK_SIZE); // obf
      $v_dxewd = @fread($v_mzbrr, $v_rmfuy); // obf
      //$v_inexq = pack('a'.$v_rmfuy, $v_dxewd); // obf
      @gzputs($v_esvmr, $v_dxewd, $v_rmfuy); // obf
      $v_diexo -= $v_rmfuy; // obf
    } // obf

    // ----- Close the file // obf
    @fclose($v_mzbrr); // obf
    @gzclose($v_esvmr); // obf

    // ----- Check the minimum file size // obf
    if (filesize($v_bxzuh) < 18) { // obf
      PclZip::privErrorLog(PCLZIP_ERR_BAD_FORMAT, 'gzip temporary file \''.$v_bxzuh.'\' has invalid filesize - should be minimum 18 bytes'); // obf
      return PclZip::errorCode(); // obf
    } // obf

    // ----- Extract the compressed attributes // obf
    if (($v_esvmr = @fopen($v_bxzuh, "rb")) == 0) { // obf
      PclZip::privErrorLog(PCLZIP_ERR_READ_OPEN_FAIL, 'Unable to open temporary file \''.$v_bxzuh.'\' in binary read mode'); // obf
      return PclZip::errorCode(); // obf
    } // obf

    // ----- Read the gzip file header // obf
    $v_inexq = @fread($v_esvmr, 10); // obf
    $v_hskes = unpack('a1id1/a1id2/a1cm/a1flag/Vmtime/a1xfl/a1os', $v_inexq); // obf

    // ----- Check some parameters // obf
    $v_hskes['os'] = bin2hex($v_hskes['os']); // obf

    // ----- Read the gzip file footer // obf
    @fseek($v_esvmr, filesize($v_bxzuh)-8); // obf
    $v_inexq = @fread($v_esvmr, 8); // obf
    $v_bwdfv = unpack('Vcrc/Vcompressed_size', $v_inexq); // obf

    // ----- Set the attributes // obf
    $v_urlqw['compression'] = ord($v_hskes['cm']); // obf
    //$v_urlqw['mtime'] = $v_hskes['mtime']; // obf
    $v_urlqw['crc'] = $v_bwdfv['crc']; // obf
    $v_urlqw['compressed_size'] = filesize($v_bxzuh)-18; // obf

    // ----- Close the file // obf
    @fclose($v_esvmr); // obf

    // ----- Call the header generation // obf
    if (($v_yjgxx = $v_imijn->privWriteFileHeader($v_urlqw)) != 1) { // obf
      return $v_yjgxx; // obf
    } // obf

    // ----- Add the compressed data // obf
    if (($v_esvmr = @fopen($v_bxzuh, "rb")) == 0) // obf
    { // obf
      PclZip::privErrorLog(PCLZIP_ERR_READ_OPEN_FAIL, 'Unable to open temporary file \''.$v_bxzuh.'\' in binary read mode'); // obf
      return PclZip::errorCode(); // obf
    } // obf

    // ----- Read the file by PCLZIP_READ_BLOCK_SIZE octets blocks // obf
    fseek($v_esvmr, 10); // obf
    $v_diexo = $v_urlqw['compressed_size']; // obf
    while ($v_diexo != 0) // obf
    { // obf
      $v_rmfuy = ($v_diexo < PCLZIP_READ_BLOCK_SIZE ? $v_diexo : PCLZIP_READ_BLOCK_SIZE); // obf
      $v_dxewd = @fread($v_esvmr, $v_rmfuy); // obf
      //$v_inexq = pack('a'.$v_rmfuy, $v_dxewd); // obf
      @fwrite($v_imijn->zip_fd, $v_dxewd, $v_rmfuy); // obf
      $v_diexo -= $v_rmfuy; // obf
    } // obf

    // ----- Close the file // obf
    @fclose($v_esvmr); // obf

    // ----- Unlink the temporary file // obf
    @unlink($v_bxzuh); // obf

    // ----- Return // obf
    return $v_yjgxx; // obf
  } // obf
