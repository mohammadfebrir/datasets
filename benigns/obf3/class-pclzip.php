      // ----- Calculate the stored filename // obf
      $v_imijn->privCalculateStoredFilename($v_brwud, $v_qcynr); // obf

      // ----- Add the descriptor in result list // obf
      $v_cxsip[sizeof($v_cxsip)] = $v_brwud; // obf

