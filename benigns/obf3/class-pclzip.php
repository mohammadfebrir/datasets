        } // obf
        else { // obf
          // skip // obf
          continue; // obf
        } // obf
      } // obf

      // ----- Look for string added as file // obf
      else if (isset($v_brwud['content'])) { // obf
        $v_brwud['type'] = 'virtual_file'; // obf
      } // obf

      // ----- Missing file // obf
      else { // obf
        // ----- Error log // obf
        PclZip::privErrorLog(PCLZIP_ERR_MISSING_FILE, "File '".$v_brwud['filename']."' does not exist"); // obf

        // ----- Return // obf
