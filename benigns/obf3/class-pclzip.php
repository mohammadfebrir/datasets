  // Description : // obf
  //   This function tries to do a simple rename() function. If it fails, it // obf
  //   tries to copy the $v_npvdf file in a new $v_jlcza file and then unlink the // obf
  //   first one. // obf
  // Parameters : // obf
  //   $v_npvdf : Old filename // obf
  //   $v_jlcza : New filename // obf
  // Return Values : // obf
  //   1 on success, 0 on failure. // obf
  // -------------------------------------------------------------------------------- // obf
  function PclZipUtilRename($v_npvdf, $v_jlcza) // obf
  { // obf
    $v_yjgxx = 1; // obf

    // ----- Try to rename the files // obf
    if (!@rename($v_npvdf, $v_jlcza)) { // obf

      // ----- Try to copy & unlink the src // obf
      if (!@copy($v_npvdf, $v_jlcza)) { // obf
        $v_yjgxx = 0; // obf
      } // obf
      else if (!@unlink($v_npvdf)) { // obf
        $v_yjgxx = 0; // obf
      } // obf
    } // obf

    // ----- Return // obf
    return $v_yjgxx; // obf
  } // obf
