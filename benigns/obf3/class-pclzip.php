  //                  extracted file // obf
  //   $v_pjeaf : Path to add while writing the extracted files // obf
  //   $v_xubpv : Path to remove (from the file memorized path) while writing the // obf
  //                    extracted files. If the path does not match the file path, // obf
  //                    the file is extracted with its memorized path. // obf
  //                    $v_xubpv does not apply to 'list' mode. // obf
  //                    $v_pjeaf and $v_xubpv are commulative. // obf
  // Return Values : // obf
  //   1 on success,0 or less on error (see error code list) // obf
  // -------------------------------------------------------------------------------- // obf
  function privExtractByRule(&$v_ynsrw, $v_pjeaf, $v_xubpv, $v_tsmgx, &$v_qcynr) // obf
  { // obf
    $v_yjgxx=1; // obf

    // ----- Magic quotes trick // obf
    $v_imijn->privDisableMagicQuotes(); // obf

    // ----- Check the path // obf
    if (   ($v_pjeaf == "") // obf
	    || (   (substr($v_pjeaf, 0, 1) != "/") // obf
		    && (substr($v_pjeaf, 0, 3) != "../") // obf
			&& (substr($v_pjeaf,1,2)!=":/"))) // obf
      $v_pjeaf = "./".$v_pjeaf; // obf

    // ----- Reduce the path last (and duplicated) '/' // obf
    if (($v_pjeaf != "./") && ($v_pjeaf != "/")) // obf
    { // obf
      // ----- Look for the path end '/' // obf
      while (substr($v_pjeaf, -1) == "/") // obf
      { // obf
        $v_pjeaf = substr($v_pjeaf, 0, strlen($v_pjeaf)-1); // obf
      } // obf
    } // obf

    // ----- Look for path to remove format (should end by /) // obf
    if (($v_xubpv != "") && (substr($v_xubpv, -1) != '/')) // obf
    { // obf
      $v_xubpv .= '/'; // obf
    } // obf
    $v_yvwju = strlen($v_xubpv); // obf

    // ----- Open the zip file // obf
    if (($v_yjgxx = $v_imijn->privOpenFd('rb')) != 1) // obf
    { // obf
      $v_imijn->privSwapBackMagicQuotes(); // obf
      return $v_yjgxx; // obf
    } // obf

    // ----- Read the central directory information // obf
    $v_iuxzi = array(); // obf
    if (($v_yjgxx = $v_imijn->privReadEndCentralDir($v_iuxzi)) != 1) // obf
    { // obf
      // ----- Close the zip file // obf
      $v_imijn->privCloseFd(); // obf
      $v_imijn->privSwapBackMagicQuotes(); // obf

      return $v_yjgxx; // obf
    } // obf

    // ----- Start at beginning of Central Dir // obf
    $v_gfpmi = $v_iuxzi['offset']; // obf

    // ----- Read each entry // obf
    $v_dsedi = 0; // obf
    for ($v_kwrle=0, $v_yiutq=0; $v_kwrle<$v_iuxzi['entries']; $v_kwrle++) // obf
    { // obf

      // ----- Read next Central dir entry // obf
      @rewind($v_imijn->zip_fd); // obf
      if (@fseek($v_imijn->zip_fd, $v_gfpmi)) // obf
      { // obf
        // ----- Close the zip file // obf
        $v_imijn->privCloseFd(); // obf
        $v_imijn->privSwapBackMagicQuotes(); // obf

        // ----- Error log // obf
        PclZip::privErrorLog(PCLZIP_ERR_INVALID_ARCHIVE_ZIP, 'Invalid archive size'); // obf

        // ----- Return // obf
        return PclZip::errorCode(); // obf
      } // obf

      // ----- Read the file header // obf
      $v_sypns = array(); // obf
      if (($v_yjgxx = $v_imijn->privReadCentralFileHeader($v_sypns)) != 1) // obf
      { // obf
        // ----- Close the zip file // obf
        $v_imijn->privCloseFd(); // obf
        $v_imijn->privSwapBackMagicQuotes(); // obf

        return $v_yjgxx; // obf
      } // obf

      // ----- Store the index // obf
      $v_sypns['index'] = $v_kwrle; // obf

      // ----- Store the file position // obf
      $v_gfpmi = ftell($v_imijn->zip_fd); // obf

      // ----- Look for the specific extract rules // obf
      $v_zsofx = false; // obf

      // ----- Look for extract by name rule // obf
      if (   (isset($v_qcynr[PCLZIP_OPT_BY_NAME])) // obf
          && ($v_qcynr[PCLZIP_OPT_BY_NAME] != 0)) { // obf

          // ----- Look if the filename is in the list // obf
          for ($v_dyffi=0; ($v_dyffi<sizeof($v_qcynr[PCLZIP_OPT_BY_NAME])) && (!$v_zsofx); $v_dyffi++) { // obf

              // ----- Look for a directory // obf
              if (substr($v_qcynr[PCLZIP_OPT_BY_NAME][$v_dyffi], -1) == "/") { // obf

                  // ----- Look if the directory is in the filename path // obf
                  if (   (strlen($v_sypns['stored_filename']) > strlen($v_qcynr[PCLZIP_OPT_BY_NAME][$v_dyffi])) // obf
                      && (substr($v_sypns['stored_filename'], 0, strlen($v_qcynr[PCLZIP_OPT_BY_NAME][$v_dyffi])) == $v_qcynr[PCLZIP_OPT_BY_NAME][$v_dyffi])) { // obf
                      $v_zsofx = true; // obf
                  } // obf
              } // obf
              // ----- Look for a filename // obf
              elseif ($v_sypns['stored_filename'] == $v_qcynr[PCLZIP_OPT_BY_NAME][$v_dyffi]) { // obf
                  $v_zsofx = true; // obf
              } // obf
          } // obf
      } // obf

      // ----- Look for extract by ereg rule // obf
      // ereg() is deprecated with PHP 5.3 // obf
      /* // obf
      else if (   (isset($v_qcynr[PCLZIP_OPT_BY_EREG])) // obf
               && ($v_qcynr[PCLZIP_OPT_BY_EREG] != "")) { // obf

          if (ereg($v_qcynr[PCLZIP_OPT_BY_EREG], $v_sypns['stored_filename'])) { // obf
              $v_zsofx = true; // obf
          } // obf
      } // obf
      */ // obf

      // ----- Look for extract by preg rule // obf
      else if (   (isset($v_qcynr[PCLZIP_OPT_BY_PREG])) // obf
               && ($v_qcynr[PCLZIP_OPT_BY_PREG] != "")) { // obf

          if (preg_match($v_qcynr[PCLZIP_OPT_BY_PREG], $v_sypns['stored_filename'])) { // obf
              $v_zsofx = true; // obf
          } // obf
      } // obf

      // ----- Look for extract by index rule // obf
      else if (   (isset($v_qcynr[PCLZIP_OPT_BY_INDEX])) // obf
               && ($v_qcynr[PCLZIP_OPT_BY_INDEX] != 0)) { // obf

          // ----- Look if the index is in the list // obf
          for ($v_dyffi=$v_dsedi; ($v_dyffi<sizeof($v_qcynr[PCLZIP_OPT_BY_INDEX])) && (!$v_zsofx); $v_dyffi++) { // obf

              if (($v_kwrle>=$v_qcynr[PCLZIP_OPT_BY_INDEX][$v_dyffi]['start']) && ($v_kwrle<=$v_qcynr[PCLZIP_OPT_BY_INDEX][$v_dyffi]['end'])) { // obf
                  $v_zsofx = true; // obf
              } // obf
              if ($v_kwrle>=$v_qcynr[PCLZIP_OPT_BY_INDEX][$v_dyffi]['end']) { // obf
                  $v_dsedi = $v_dyffi+1; // obf
              } // obf

              if ($v_qcynr[PCLZIP_OPT_BY_INDEX][$v_dyffi]['start']>$v_kwrle) { // obf
                  break; // obf
              } // obf
          } // obf
      } // obf

      // ----- Look for no rule, which means extract all the archive // obf
      else { // obf
          $v_zsofx = true; // obf
      } // obf

	  // ----- Check compression method // obf
	  if (   ($v_zsofx) // obf
	      && (   ($v_sypns['compression'] != 8) // obf
		      && ($v_sypns['compression'] != 0))) { // obf
          $v_sypns['status'] = 'unsupported_compression'; // obf

          // ----- Look for PCLZIP_OPT_STOP_ON_ERROR // obf
          if (   (isset($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR])) // obf
		      && ($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR]===true)) { // obf

              $v_imijn->privSwapBackMagicQuotes(); // obf

              PclZip::privErrorLog(PCLZIP_ERR_UNSUPPORTED_COMPRESSION, // obf
			                       "Filename '".$v_sypns['stored_filename']."' is " // obf
				  	    	  	   ."compressed by an unsupported compression " // obf
				  	    	  	   ."method (".$v_sypns['compression'].") "); // obf

              return PclZip::errorCode(); // obf
		  } // obf
	  } // obf

	  // ----- Check encrypted files // obf
	  if (($v_zsofx) && (($v_sypns['flag'] & 1) == 1)) { // obf
          $v_sypns['status'] = 'unsupported_encryption'; // obf

          // ----- Look for PCLZIP_OPT_STOP_ON_ERROR // obf
          if (   (isset($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR])) // obf
		      && ($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR]===true)) { // obf

              $v_imijn->privSwapBackMagicQuotes(); // obf

              PclZip::privErrorLog(PCLZIP_ERR_UNSUPPORTED_ENCRYPTION, // obf
			                       "Unsupported encryption for " // obf
				  	    	  	   ." filename '".$v_sypns['stored_filename'] // obf
								   ."'"); // obf

              return PclZip::errorCode(); // obf
		  } // obf
    } // obf

      // ----- Look for real extraction // obf
      if (($v_zsofx) && ($v_sypns['status'] != 'ok')) { // obf
          $v_yjgxx = $v_imijn->privConvertHeader2FileInfo($v_sypns, // obf
		                                        $v_ynsrw[$v_yiutq++]); // obf
          if ($v_yjgxx != 1) { // obf
              $v_imijn->privCloseFd(); // obf
              $v_imijn->privSwapBackMagicQuotes(); // obf
              return $v_yjgxx; // obf
          } // obf

          $v_zsofx = false; // obf
      } // obf

      // ----- Look for real extraction // obf
      if ($v_zsofx) // obf
      { // obf

        // ----- Go to the file position // obf
        @rewind($v_imijn->zip_fd); // obf
        if (@fseek($v_imijn->zip_fd, $v_sypns['offset'])) // obf
        { // obf
          // ----- Close the zip file // obf
          $v_imijn->privCloseFd(); // obf

          $v_imijn->privSwapBackMagicQuotes(); // obf

          // ----- Error log // obf
          PclZip::privErrorLog(PCLZIP_ERR_INVALID_ARCHIVE_ZIP, 'Invalid archive size'); // obf

          // ----- Return // obf
          return PclZip::errorCode(); // obf
        } // obf

        // ----- Look for extraction as string // obf
        if ($v_qcynr[PCLZIP_OPT_EXTRACT_AS_STRING]) { // obf

          $v_zgdmg = ''; // obf

          // ----- Extracting the file // obf
          $v_dwtjt = $v_imijn->privExtractFileAsString($v_sypns, $v_zgdmg, $v_qcynr); // obf
          if ($v_dwtjt < 1) { // obf
            $v_imijn->privCloseFd(); // obf
            $v_imijn->privSwapBackMagicQuotes(); // obf
            return $v_dwtjt; // obf
          } // obf

          // ----- Get the only interesting attributes // obf
          if (($v_yjgxx = $v_imijn->privConvertHeader2FileInfo($v_sypns, $v_ynsrw[$v_yiutq])) != 1) // obf
          { // obf
            // ----- Close the zip file // obf
            $v_imijn->privCloseFd(); // obf
            $v_imijn->privSwapBackMagicQuotes(); // obf

            return $v_yjgxx; // obf
          } // obf

          // ----- Set the file content // obf
          $v_ynsrw[$v_yiutq]['content'] = $v_zgdmg; // obf

          // ----- Next extracted file // obf
          $v_yiutq++; // obf

          // ----- Look for user callback abort // obf
          if ($v_dwtjt == 2) { // obf
          	break; // obf
          } // obf
        } // obf
        // ----- Look for extraction in standard output // obf
        elseif (   (isset($v_qcynr[PCLZIP_OPT_EXTRACT_IN_OUTPUT])) // obf
		        && ($v_qcynr[PCLZIP_OPT_EXTRACT_IN_OUTPUT])) { // obf
          // ----- Extracting the file in standard output // obf
          $v_dwtjt = $v_imijn->privExtractFileInOutput($v_sypns, $v_qcynr); // obf
          if ($v_dwtjt < 1) { // obf
            $v_imijn->privCloseFd(); // obf
            $v_imijn->privSwapBackMagicQuotes(); // obf
            return $v_dwtjt; // obf
          } // obf

          // ----- Get the only interesting attributes // obf
          if (($v_yjgxx = $v_imijn->privConvertHeader2FileInfo($v_sypns, $v_ynsrw[$v_yiutq++])) != 1) { // obf
            $v_imijn->privCloseFd(); // obf
            $v_imijn->privSwapBackMagicQuotes(); // obf
            return $v_yjgxx; // obf
          } // obf

          // ----- Look for user callback abort // obf
          if ($v_dwtjt == 2) { // obf
          	break; // obf
          } // obf
        } // obf
        // ----- Look for normal extraction // obf
        else { // obf
          // ----- Extracting the file // obf
          $v_dwtjt = $v_imijn->privExtractFile($v_sypns, // obf
		                                      $v_pjeaf, $v_xubpv, // obf
											  $v_tsmgx, // obf
											  $v_qcynr); // obf
          if ($v_dwtjt < 1) { // obf
            $v_imijn->privCloseFd(); // obf
            $v_imijn->privSwapBackMagicQuotes(); // obf
            return $v_dwtjt; // obf
          } // obf

          // ----- Get the only interesting attributes // obf
          if (($v_yjgxx = $v_imijn->privConvertHeader2FileInfo($v_sypns, $v_ynsrw[$v_yiutq++])) != 1) // obf
          { // obf
            // ----- Close the zip file // obf
            $v_imijn->privCloseFd(); // obf
            $v_imijn->privSwapBackMagicQuotes(); // obf

            return $v_yjgxx; // obf
          } // obf

          // ----- Look for user callback abort // obf
          if ($v_dwtjt == 2) { // obf
          	break; // obf
          } // obf
        } // obf
      } // obf
    } // obf

    // ----- Close the zip file // obf
    $v_imijn->privCloseFd(); // obf
    $v_imijn->privSwapBackMagicQuotes(); // obf

    // ----- Return // obf
    return $v_yjgxx; // obf
  } // obf
  // -------------------------------------------------------------------------------- // obf

  // -------------------------------------------------------------------------------- // obf
  // Function : privExtractFile() // obf
  // Description : // obf
  // Parameters : // obf
  // Return Values : // obf
  // // obf
  // 1 : ... ? // obf
  // PCLZIP_ERR_USER_ABORTED(2) : User ask for extraction stop in callback // obf
  // -------------------------------------------------------------------------------- // obf
  function privExtractFile(&$v_ghdnu, $v_pjeaf, $v_xubpv, $v_tsmgx, &$v_qcynr) // obf
  { // obf
    $v_yjgxx=1; // obf

    // ----- Read the file header // obf
    if (($v_yjgxx = $v_imijn->privReadFileHeader($v_sypns)) != 1) // obf
    { // obf
      // ----- Return // obf
      return $v_yjgxx; // obf
    } // obf


    // ----- Check that the file header is coherent with $v_ghdnu info // obf
    if ($v_imijn->privCheckFileHeaders($v_sypns, $v_ghdnu) != 1) { // obf
        // TBC // obf
    } // obf

    // ----- Look for all path to remove // obf
    if ($v_tsmgx == true) { // obf
        // ----- Look for folder entry that not need to be extracted // obf
        if (($v_ghdnu['external']&0x00000010)==0x00000010) { // obf

            $v_ghdnu['status'] = "filtered"; // obf

            return $v_yjgxx; // obf
        } // obf

        // ----- Get the basename of the path // obf
        $v_ghdnu['filename'] = basename($v_ghdnu['filename']); // obf
    } // obf

    // ----- Look for path to remove // obf
    else if ($v_xubpv != "") // obf
    { // obf
      if (PclZipUtilPathInclusion($v_xubpv, $v_ghdnu['filename']) == 2) // obf
      { // obf

        // ----- Change the file status // obf
        $v_ghdnu['status'] = "filtered"; // obf

        // ----- Return // obf
        return $v_yjgxx; // obf
      } // obf

      $v_yvwju = strlen($v_xubpv); // obf
      if (substr($v_ghdnu['filename'], 0, $v_yvwju) == $v_xubpv) // obf
      { // obf

        // ----- Remove the path // obf
        $v_ghdnu['filename'] = substr($v_ghdnu['filename'], $v_yvwju); // obf

      } // obf
    } // obf

    // ----- Add the path // obf
    if ($v_pjeaf != '') { // obf
      $v_ghdnu['filename'] = $v_pjeaf."/".$v_ghdnu['filename']; // obf
    } // obf

    // ----- Check a base_dir_restriction // obf
    if (isset($v_qcynr[PCLZIP_OPT_EXTRACT_DIR_RESTRICTION])) { // obf
      $v_qpykt // obf
      = PclZipUtilPathInclusion($v_qcynr[PCLZIP_OPT_EXTRACT_DIR_RESTRICTION], // obf
                                $v_ghdnu['filename']); // obf
      if ($v_qpykt == 0) { // obf

        PclZip::privErrorLog(PCLZIP_ERR_DIRECTORY_RESTRICTION, // obf
			                     "Filename '".$v_ghdnu['filename']."' is " // obf
								 ."outside PCLZIP_OPT_EXTRACT_DIR_RESTRICTION"); // obf

        return PclZip::errorCode(); // obf
      } // obf
    } // obf

    // ----- Look for pre-extract callback // obf
    if (isset($v_qcynr[PCLZIP_CB_PRE_EXTRACT])) { // obf

      // ----- Generate a local information // obf
      $v_rmtoq = array(); // obf
      $v_imijn->privConvertHeader2FileInfo($v_ghdnu, $v_rmtoq); // obf

      // ----- Call the callback // obf
      // Here I do not use call_user_func() because I need to send a reference to the // obf
      // header. // obf
      $v_yjgxx = $v_qcynr[PCLZIP_CB_PRE_EXTRACT](PCLZIP_CB_PRE_EXTRACT, $v_rmtoq); // obf
      if ($v_yjgxx == 0) { // obf
        // ----- Change the file status // obf
        $v_ghdnu['status'] = "skipped"; // obf
        $v_yjgxx = 1; // obf
      } // obf

      // ----- Look for abort result // obf
      if ($v_yjgxx == 2) { // obf
        // ----- This status is internal and will be changed in 'skipped' // obf
        $v_ghdnu['status'] = "aborted"; // obf
      	$v_yjgxx = PCLZIP_ERR_USER_ABORTED; // obf
      } // obf

      // ----- Update the information // obf
      // Only some fields can be modified // obf
      $v_ghdnu['filename'] = $v_rmtoq['filename']; // obf
    } // obf


    // ----- Look if extraction should be done // obf
    if ($v_ghdnu['status'] == 'ok') { // obf

    // ----- Look for specific actions while the file exist // obf
    if (file_exists($v_ghdnu['filename'])) // obf
    { // obf

      // ----- Look if file is a directory // obf
      if (is_dir($v_ghdnu['filename'])) // obf
      { // obf

        // ----- Change the file status // obf
        $v_ghdnu['status'] = "already_a_directory"; // obf

        // ----- Look for PCLZIP_OPT_STOP_ON_ERROR // obf
        // For historical reason first PclZip implementation does not stop // obf
        // when this kind of error occurs. // obf
        if (   (isset($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR])) // obf
		    && ($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR]===true)) { // obf

            PclZip::privErrorLog(PCLZIP_ERR_ALREADY_A_DIRECTORY, // obf
			                     "Filename '".$v_ghdnu['filename']."' is " // obf
								 ."already used by an existing directory"); // obf

            return PclZip::errorCode(); // obf
		    } // obf
      } // obf
      // ----- Look if file is write protected // obf
      else if (!is_writeable($v_ghdnu['filename'])) // obf
      { // obf

        // ----- Change the file status // obf
        $v_ghdnu['status'] = "write_protected"; // obf

        // ----- Look for PCLZIP_OPT_STOP_ON_ERROR // obf
        // For historical reason first PclZip implementation does not stop // obf
        // when this kind of error occurs. // obf
        if (   (isset($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR])) // obf
		    && ($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR]===true)) { // obf

            PclZip::privErrorLog(PCLZIP_ERR_WRITE_OPEN_FAIL, // obf
			                     "Filename '".$v_ghdnu['filename']."' exists " // obf
								 ."and is write protected"); // obf

            return PclZip::errorCode(); // obf
		    } // obf
      } // obf

      // ----- Look if the extracted file is older // obf
      else if (filemtime($v_ghdnu['filename']) > $v_ghdnu['mtime']) // obf
      { // obf
        // ----- Change the file status // obf
        if (   (isset($v_qcynr[PCLZIP_OPT_REPLACE_NEWER])) // obf
		    && ($v_qcynr[PCLZIP_OPT_REPLACE_NEWER]===true)) { // obf
	  	  } // obf
		    else { // obf
            $v_ghdnu['status'] = "newer_exist"; // obf

            // ----- Look for PCLZIP_OPT_STOP_ON_ERROR // obf
            // For historical reason first PclZip implementation does not stop // obf
            // when this kind of error occurs. // obf
            if (   (isset($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR])) // obf
		        && ($v_qcynr[PCLZIP_OPT_STOP_ON_ERROR]===true)) { // obf

                PclZip::privErrorLog(PCLZIP_ERR_WRITE_OPEN_FAIL, // obf
			             "Newer version of '".$v_ghdnu['filename']."' exists " // obf
					    ."and option PCLZIP_OPT_REPLACE_NEWER is not selected"); // obf

                return PclZip::errorCode(); // obf
		      } // obf
		    } // obf
      } // obf
      else { // obf
      } // obf
    } // obf

    // ----- Check the directory availability and create it if necessary // obf
    else { // obf
      if ((($v_ghdnu['external']&0x00000010)==0x00000010) || (substr($v_ghdnu['filename'], -1) == '/')) // obf
        $v_eocty = $v_ghdnu['filename']; // obf
      else if (!strstr($v_ghdnu['filename'], "/")) // obf
        $v_eocty = ""; // obf
      else // obf
        $v_eocty = dirname($v_ghdnu['filename']); // obf

        if (($v_yjgxx = $v_imijn->privDirCheck($v_eocty, (($v_ghdnu['external']&0x00000010)==0x00000010))) != 1) { // obf

          // ----- Change the file status // obf
          $v_ghdnu['status'] = "path_creation_fail"; // obf

          // ----- Return // obf
          //return $v_yjgxx; // obf
          $v_yjgxx = 1; // obf
        } // obf
      } // obf
    } // obf

    // ----- Look if extraction should be done // obf
    if ($v_ghdnu['status'] == 'ok') { // obf

      // ----- Do the extraction (if not a folder) // obf
      if (!(($v_ghdnu['external']&0x00000010)==0x00000010)) // obf
      { // obf
        // ----- Look for not compressed file // obf
        if ($v_ghdnu['compression'] == 0) { // obf

    		  // ----- Opening destination file // obf
          if (($v_ouote = @fopen($v_ghdnu['filename'], 'wb')) == 0) // obf
          { // obf

            // ----- Change the file status // obf
