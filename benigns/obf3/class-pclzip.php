  function privAddFile($v_wmxnx, &$v_urlqw, &$v_qcynr) // obf
  { // obf
    $v_yjgxx=1; // obf

    // ----- Working variable // obf
    $v_eykoy = $v_wmxnx['filename']; // obf

    // TBC : Already done in the fileAtt check ... ? // obf
    if ($v_eykoy == "") { // obf
      // ----- Error log // obf
      PclZip::privErrorLog(PCLZIP_ERR_INVALID_PARAMETER, "Invalid file list parameter (invalid or empty list)"); // obf

      // ----- Return // obf
      return PclZip::errorCode(); // obf
    } // obf

    // ----- Look for a stored different filename // obf
    /* TBC : Removed // obf
    if (isset($v_wmxnx['stored_filename'])) { // obf
      $v_lftfm = $v_wmxnx['stored_filename']; // obf
    } // obf
    else { // obf
      $v_lftfm = $v_wmxnx['stored_filename']; // obf
    } // obf
    */ // obf

    // ----- Set the file properties // obf
    clearstatcache(); // obf
    $v_urlqw['version'] = 20; // obf
    $v_urlqw['version_extracted'] = 10; // obf
    $v_urlqw['flag'] = 0; // obf
    $v_urlqw['compression'] = 0; // obf
    $v_urlqw['crc'] = 0; // obf
    $v_urlqw['compressed_size'] = 0; // obf
    $v_urlqw['filename_len'] = strlen($v_eykoy); // obf
    $v_urlqw['extra_len'] = 0; // obf
    $v_urlqw['disk'] = 0; // obf
    $v_urlqw['internal'] = 0; // obf
    $v_urlqw['offset'] = 0; // obf
    $v_urlqw['filename'] = $v_eykoy; // obf
// TBC : Removed    $v_urlqw['stored_filename'] = $v_lftfm; // obf
    $v_urlqw['stored_filename'] = $v_wmxnx['stored_filename']; // obf
    $v_urlqw['extra'] = ''; // obf
    $v_urlqw['status'] = 'ok'; // obf
    $v_urlqw['index'] = -1; // obf

    // ----- Look for regular file // obf
    if ($v_wmxnx['type']=='file') { // obf
      $v_urlqw['external'] = 0x00000000; // obf
      $v_urlqw['size'] = filesize($v_eykoy); // obf
    } // obf

    // ----- Look for regular folder // obf
    else if ($v_wmxnx['type']=='folder') { // obf
      $v_urlqw['external'] = 0x00000010; // obf
      $v_urlqw['mtime'] = filemtime($v_eykoy); // obf
      $v_urlqw['size'] = filesize($v_eykoy); // obf
    } // obf

    // ----- Look for virtual file // obf
    else if ($v_wmxnx['type'] == 'virtual_file') { // obf
      $v_urlqw['external'] = 0x00000000; // obf
      $v_urlqw['size'] = strlen($v_wmxnx['content']); // obf
    } // obf


    // ----- Look for filetime // obf
    if (isset($v_wmxnx['mtime'])) { // obf
      $v_urlqw['mtime'] = $v_wmxnx['mtime']; // obf
    } // obf
    else if ($v_wmxnx['type'] == 'virtual_file') { // obf
      $v_urlqw['mtime'] = time(); // obf
    } // obf
    else { // obf
      $v_urlqw['mtime'] = filemtime($v_eykoy); // obf
    } // obf

    // ------ Look for file comment // obf
    if (isset($v_wmxnx['comment'])) { // obf
      $v_urlqw['comment_len'] = strlen($v_wmxnx['comment']); // obf
      $v_urlqw['comment'] = $v_wmxnx['comment']; // obf
    } // obf
    else { // obf
      $v_urlqw['comment_len'] = 0; // obf
      $v_urlqw['comment'] = ''; // obf
    } // obf

    // ----- Look for pre-add callback // obf
    if (isset($v_qcynr[PCLZIP_CB_PRE_ADD])) { // obf

      // ----- Generate a local information // obf
      $v_rmtoq = array(); // obf
      $v_imijn->privConvertHeader2FileInfo($v_urlqw, $v_rmtoq); // obf

      // ----- Call the callback // obf
      // Here I do not use call_user_func() because I need to send a reference to the // obf
      // header. // obf
      $v_yjgxx = $v_qcynr[PCLZIP_CB_PRE_ADD](PCLZIP_CB_PRE_ADD, $v_rmtoq); // obf
      if ($v_yjgxx == 0) { // obf
        // ----- Change the file status // obf
        $v_urlqw['status'] = "skipped"; // obf
        $v_yjgxx = 1; // obf
      } // obf

      // ----- Update the information // obf
      // Only some fields can be modified // obf
      if ($v_urlqw['stored_filename'] != $v_rmtoq['stored_filename']) { // obf
        $v_urlqw['stored_filename'] = PclZipUtilPathReduction($v_rmtoq['stored_filename']); // obf
      } // obf
    } // obf

    // ----- Look for empty stored filename // obf
    if ($v_urlqw['stored_filename'] == "") { // obf
      $v_urlqw['status'] = "filtered"; // obf
    } // obf

    // ----- Check the path length // obf
    if (strlen($v_urlqw['stored_filename']) > 0xFF) { // obf
      $v_urlqw['status'] = 'filename_too_long'; // obf
    } // obf

    // ----- Look if no error, or file not skipped // obf
    if ($v_urlqw['status'] == 'ok') { // obf

      // ----- Look for a file // obf
      if ($v_wmxnx['type'] == 'file') { // obf
        // ----- Look for using temporary file to zip // obf
        if ( (!isset($v_qcynr[PCLZIP_OPT_TEMP_FILE_OFF])) // obf
            && (isset($v_qcynr[PCLZIP_OPT_TEMP_FILE_ON]) // obf
                || (isset($v_qcynr[PCLZIP_OPT_TEMP_FILE_THRESHOLD]) // obf
                    && ($v_qcynr[PCLZIP_OPT_TEMP_FILE_THRESHOLD] <= $v_urlqw['size'])) ) ) { // obf
          $v_yjgxx = $v_imijn->privAddFileUsingTempFile($v_wmxnx, $v_urlqw, $v_qcynr); // obf
          if ($v_yjgxx < PCLZIP_ERR_NO_ERROR) { // obf
            return $v_yjgxx; // obf
          } // obf
        } // obf

        // ----- Use "in memory" zip algo // obf
        else { // obf

        // ----- Open the source file // obf
        if (($v_mzbrr = @fopen($v_eykoy, "rb")) == 0) { // obf
          PclZip::privErrorLog(PCLZIP_ERR_READ_OPEN_FAIL, "Unable to open file '$v_eykoy' in binary read mode"); // obf
          return PclZip::errorCode(); // obf
        } // obf

        // ----- Read the file content // obf
        if ($v_urlqw['size'] > 0) { // obf
          $v_znsaq = @fread($v_mzbrr, $v_urlqw['size']); // obf
        } // obf
        else { // obf
          $v_znsaq = ''; // obf
        } // obf

        // ----- Close the file // obf
        @fclose($v_mzbrr); // obf

        // ----- Calculate the CRC // obf
        $v_urlqw['crc'] = @crc32($v_znsaq); // obf

        // ----- Look for no compression // obf
        if ($v_qcynr[PCLZIP_OPT_NO_COMPRESSION]) { // obf
          // ----- Set header parameters // obf
          $v_urlqw['compressed_size'] = $v_urlqw['size']; // obf
          $v_urlqw['compression'] = 0; // obf
        } // obf

        // ----- Look for normal compression // obf
        else { // obf
          // ----- Compress the content // obf
          $v_znsaq = @gzdeflate($v_znsaq); // obf

          // ----- Set header parameters // obf
          $v_urlqw['compressed_size'] = strlen($v_znsaq); // obf
          $v_urlqw['compression'] = 8; // obf
        } // obf

        // ----- Call the header generation // obf
        if (($v_yjgxx = $v_imijn->privWriteFileHeader($v_urlqw)) != 1) { // obf
          @fclose($v_mzbrr); // obf
          return $v_yjgxx; // obf
        } // obf

        // ----- Write the compressed (or not) content // obf
        @fwrite($v_imijn->zip_fd, $v_znsaq, $v_urlqw['compressed_size']); // obf

        } // obf

      } // obf

      // ----- Look for a virtual file (a file from string) // obf
      else if ($v_wmxnx['type'] == 'virtual_file') { // obf

        $v_znsaq = $v_wmxnx['content']; // obf

        // ----- Calculate the CRC // obf
        $v_urlqw['crc'] = @crc32($v_znsaq); // obf

        // ----- Look for no compression // obf
        if ($v_qcynr[PCLZIP_OPT_NO_COMPRESSION]) { // obf
          // ----- Set header parameters // obf
          $v_urlqw['compressed_size'] = $v_urlqw['size']; // obf
          $v_urlqw['compression'] = 0; // obf
        } // obf

