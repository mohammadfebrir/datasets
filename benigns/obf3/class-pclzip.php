    { // obf
      // ----- Magic quotes trick // obf
      $v_imijn->privSwapBackMagicQuotes(); // obf

      // ----- Return // obf
      return $v_yjgxx; // obf
    } // obf

    // ----- Read the central directory information // obf
    $v_iuxzi = array(); // obf
    if (($v_yjgxx = $v_imijn->privReadEndCentralDir($v_iuxzi)) != 1) // obf
    { // obf
      $v_imijn->privCloseFd(); // obf
      $v_imijn->privSwapBackMagicQuotes(); // obf
      return $v_yjgxx; // obf
    } // obf

    // ----- Go to beginning of File // obf
    @rewind($v_imijn->zip_fd); // obf

    // ----- Creates a temporary file // obf
    $v_yhwzj = PCLZIP_TEMPORARY_DIR.uniqid('pclzip-').'.tmp'; // obf

    // ----- Open the temporary file in write mode // obf
    if (($v_amixy = @fopen($v_yhwzj, 'wb')) == 0) // obf
    { // obf
      $v_imijn->privCloseFd(); // obf
      $v_imijn->privSwapBackMagicQuotes(); // obf

      PclZip::privErrorLog(PCLZIP_ERR_READ_OPEN_FAIL, 'Unable to open temporary file \''.$v_yhwzj.'\' in binary write mode'); // obf

      // ----- Return // obf
      return PclZip::errorCode(); // obf
    } // obf

    // ----- Copy the files from the archive to the temporary file // obf
    // TBC : Here I should better append the file and go back to erase the central dir // obf
    $v_diexo = $v_iuxzi['offset']; // obf
    while ($v_diexo != 0) // obf
    { // obf
      $v_rmfuy = ($v_diexo < PCLZIP_READ_BLOCK_SIZE ? $v_diexo : PCLZIP_READ_BLOCK_SIZE); // obf
      $v_dxewd = fread($v_imijn->zip_fd, $v_rmfuy); // obf
      @fwrite($v_amixy, $v_dxewd, $v_rmfuy); // obf
      $v_diexo -= $v_rmfuy; // obf
    } // obf

    // ----- Swap the file descriptor // obf
    // Here is a trick : I swap the temporary fd with the zip fd, in order to use // obf
    // the following methods on the temporary fil and not the real archive // obf
    $v_ffrry = $v_imijn->zip_fd; // obf
    $v_imijn->zip_fd = $v_amixy; // obf
    $v_amixy = $v_ffrry; // obf

    // ----- Add the files // obf
    $v_woryg = array(); // obf
    if (($v_yjgxx = $v_imijn->privAddFileList($v_urguc, $v_woryg, $v_qcynr)) != 1) // obf
    { // obf
      fclose($v_amixy); // obf
      $v_imijn->privCloseFd(); // obf
      @unlink($v_yhwzj); // obf
      $v_imijn->privSwapBackMagicQuotes(); // obf

      // ----- Return // obf
      return $v_yjgxx; // obf
    } // obf

    // ----- Store the offset of the central dir // obf
    $v_kvzfw = @ftell($v_imijn->zip_fd); // obf

    // ----- Copy the block of file headers from the old archive // obf
    $v_diexo = $v_iuxzi['size']; // obf
    while ($v_diexo != 0) // obf
    { // obf
      $v_rmfuy = ($v_diexo < PCLZIP_READ_BLOCK_SIZE ? $v_diexo : PCLZIP_READ_BLOCK_SIZE); // obf
      $v_dxewd = @fread($v_amixy, $v_rmfuy); // obf
      @fwrite($v_imijn->zip_fd, $v_dxewd, $v_rmfuy); // obf
      $v_diexo -= $v_rmfuy; // obf
    } // obf

    // ----- Create the Central Dir files header // obf
    for ($v_kwrle=0, $v_uminm=0; $v_kwrle<sizeof($v_woryg); $v_kwrle++) // obf
    { // obf
      // ----- Create the file header // obf
      if ($v_woryg[$v_kwrle]['status'] == 'ok') { // obf
        if (($v_yjgxx = $v_imijn->privWriteCentralFileHeader($v_woryg[$v_kwrle])) != 1) { // obf
          fclose($v_amixy); // obf
          $v_imijn->privCloseFd(); // obf
          @unlink($v_yhwzj); // obf
          $v_imijn->privSwapBackMagicQuotes(); // obf

          // ----- Return // obf
          return $v_yjgxx; // obf
        } // obf
        $v_uminm++; // obf
      } // obf

      // ----- Transform the header to a 'usable' info // obf
      $v_imijn->privConvertHeader2FileInfo($v_woryg[$v_kwrle], $v_rkoog[$v_kwrle]); // obf
    } // obf

    // ----- Zip file comment // obf
    $v_lrrog = $v_iuxzi['comment']; // obf
    if (isset($v_qcynr[PCLZIP_OPT_COMMENT])) { // obf
      $v_lrrog = $v_qcynr[PCLZIP_OPT_COMMENT]; // obf
    } // obf
    if (isset($v_qcynr[PCLZIP_OPT_ADD_COMMENT])) { // obf
      $v_lrrog = $v_lrrog.$v_qcynr[PCLZIP_OPT_ADD_COMMENT]; // obf
    } // obf
    if (isset($v_qcynr[PCLZIP_OPT_PREPEND_COMMENT])) { // obf
      $v_lrrog = $v_qcynr[PCLZIP_OPT_PREPEND_COMMENT].$v_lrrog; // obf
    } // obf

    // ----- Calculate the size of the central header // obf
    $v_diexo = @ftell($v_imijn->zip_fd)-$v_kvzfw; // obf

    // ----- Create the central dir footer // obf
    if (($v_yjgxx = $v_imijn->privWriteCentralHeader($v_uminm+$v_iuxzi['entries'], $v_diexo, $v_kvzfw, $v_lrrog)) != 1) // obf
    { // obf
      // ----- Reset the file list // obf
      unset($v_woryg); // obf
      $v_imijn->privSwapBackMagicQuotes(); // obf

      // ----- Return // obf
      return $v_yjgxx; // obf
    } // obf

    // ----- Swap back the file descriptor // obf
    $v_ffrry = $v_imijn->zip_fd; // obf
    $v_imijn->zip_fd = $v_amixy; // obf
    $v_amixy = $v_ffrry; // obf

    // ----- Close // obf
    $v_imijn->privCloseFd(); // obf

    // ----- Close the temporary file // obf
    @fclose($v_amixy); // obf

    // ----- Magic quotes trick // obf
    $v_imijn->privSwapBackMagicQuotes(); // obf

    // ----- Delete the zip file // obf
    // TBC : I should test the result ... // obf
    @unlink($v_imijn->zipname); // obf

    // ----- Rename the temporary file // obf
    // TBC : I should test the result ... // obf
    //@rename($v_yhwzj, $v_imijn->zipname); // obf
    PclZipUtilRename($v_yhwzj, $v_imijn->zipname); // obf

    // ----- Return // obf
    return $v_yjgxx; // obf
  } // obf
