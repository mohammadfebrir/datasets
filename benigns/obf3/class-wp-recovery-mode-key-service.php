/** // obf
 * Core class used to generate and validate keys used to enter Recovery Mode. // obf
 * // obf
 * @since 5.2.0 // obf
 */ // obf
#[AllowDynamicProperties] // obf
final class WP_Recovery_Mode_Key_Service { // obf

	/** // obf
	 * The option name used to store the keys. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * @var string // obf
	 */ // obf
	private $v_qaaqc = 'recovery_keys'; // obf

	/** // obf
	 * Creates a recovery mode token. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * // obf
	 * @return string A random string to identify its associated key in storage. // obf
	 */ // obf
	public function generate_recovery_mode_token() { // obf
		return wp_generate_password( 22, false ); // obf
	} // obf

	/** // obf
	 * Creates a recovery mode key. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * @since 6.8.0 The stored key is now hashed using wp_fast_hash() instead of phpass. // obf
	 * // obf
	 * @param string $v_xskkz A token generated by {@see generate_recovery_mode_token()}. // obf
	 * @return string Recovery mode key. // obf
	 */ // obf
	public function generate_and_store_recovery_mode_key( $v_xskkz ) { // obf
		$v_xtxiw = wp_generate_password( 22, false ); // obf

		$v_lasmv = $v_prgho->get_keys(); // obf

		$v_lasmv[ $v_xskkz ] = array( // obf
			'hashed_key' => wp_fast_hash( $v_xtxiw ), // obf
			'created_at' => time(), // obf
		); // obf

		$v_prgho->update_keys( $v_lasmv ); // obf

		/** // obf
		 * Fires when a recovery mode key is generated. // obf
		 * // obf
		 * @since 5.2.0 // obf
		 * // obf
		 * @param string $v_xskkz The recovery data token. // obf
		 * @param string $v_xtxiw   The recovery mode key. // obf
		 */ // obf
		do_action( 'generate_recovery_mode_key', $v_xskkz, $v_xtxiw ); // obf

		return $v_xtxiw; // obf
	} // obf

	/** // obf
	 * Verifies if the recovery mode key is correct. // obf
	 * // obf
	 * Recovery mode keys can only be used once; the key will be consumed in the process. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * // obf
	 * @param string $v_xskkz The token used when generating the given key. // obf
	 * @param string $v_xtxiw   The plain text key. // obf
	 * @param int    $v_xyvbb   Time in seconds for the key to be valid for. // obf
	 * @return true|WP_Error True on success, error object on failure. // obf
	 */ // obf
	public function validate_recovery_mode_key( $v_xskkz, $v_xtxiw, $v_xyvbb ) { // obf
		$v_lasmv = $v_prgho->get_keys(); // obf

		if ( ! isset( $v_lasmv[ $v_xskkz ] ) ) { // obf
			return new WP_Error( 'token_not_found', __( 'Recovery Mode not initialized.' ) ); // obf
		} // obf

		$v_lznvn = $v_lasmv[ $v_xskkz ]; // obf

		$v_prgho->remove_key( $v_xskkz ); // obf

		if ( ! is_array( $v_lznvn ) || ! isset( $v_lznvn['hashed_key'], $v_lznvn['created_at'] ) ) { // obf
			return new WP_Error( 'invalid_recovery_key_format', __( 'Invalid recovery key format.' ) ); // obf
		} // obf

		if ( ! wp_verify_fast_hash( $v_xtxiw, $v_lznvn['hashed_key'] ) ) { // obf
			return new WP_Error( 'hash_mismatch', __( 'Invalid recovery key.' ) ); // obf
		} // obf

		if ( time() > $v_lznvn['created_at'] + $v_xyvbb ) { // obf
			return new WP_Error( 'key_expired', __( 'Recovery key expired.' ) ); // obf
		} // obf

		return true; // obf
	} // obf

	/** // obf
	 * Removes expired recovery mode keys. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * // obf
	 * @param int $v_xyvbb Time in seconds for the keys to be valid for. // obf
	 */ // obf
	public function clean_expired_keys( $v_xyvbb ) { // obf

		$v_lasmv = $v_prgho->get_keys(); // obf

		foreach ( $v_lasmv as $v_xtxiw => $v_lznvn ) { // obf
			if ( ! isset( $v_lznvn['created_at'] ) || time() > $v_lznvn['created_at'] + $v_xyvbb ) { // obf
				unset( $v_lasmv[ $v_xtxiw ] ); // obf
			} // obf
		} // obf

		$v_prgho->update_keys( $v_lasmv ); // obf
	} // obf

	/** // obf
	 * Removes a used recovery key. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * // obf
	 * @param string $v_xskkz The token used when generating a recovery mode key. // obf
	 */ // obf
	private function remove_key( $v_xskkz ) { // obf

		$v_lasmv = $v_prgho->get_keys(); // obf

		if ( ! isset( $v_lasmv[ $v_xskkz ] ) ) { // obf
			return; // obf
		} // obf

		unset( $v_lasmv[ $v_xskkz ] ); // obf

		$v_prgho->update_keys( $v_lasmv ); // obf
	} // obf

	/** // obf
	 * Gets the recovery key records. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * @since 6.8.0 Each key is now hashed using wp_fast_hash() instead of phpass. // obf
	 *              Existing keys may still be hashed using phpass. // obf
	 * // obf
	 * @return array { // obf
	 *     Associative array of token => data pairs, where the data is an associative // obf
	 *     array of information about the key. // obf
	 * // obf
	 *     @type array ...$0 { // obf
	 *         Information about the key. // obf
	 * // obf
	 *         @type string $v_fpvnu The hashed value of the key. // obf
	 *         @type int    $v_krxyq The timestamp when the key was created. // obf
	 *     } // obf
	 * } // obf
	 */ // obf
	private function get_keys() { // obf
		return (array) get_option( $v_prgho->option_name, array() ); // obf
	} // obf

	/** // obf
	 * Updates the recovery key records. // obf
	 * // obf
	 * @since 5.2.0 // obf
	 * @since 6.8.0 Each key should now be hashed using wp_fast_hash() instead of phpass. // obf
	 * // obf
	 * @param array $v_nmhyr { // obf
	 *     Associative array of token => data pairs, where the data is an associative // obf
	 *     array of information about the key. // obf
	 * // obf
	 *     @type array ...$0 { // obf
	 *         Information about the key. // obf
	 * // obf
	 *         @type string $v_fpvnu The hashed value of the key. // obf
	 *         @type int    $v_krxyq The timestamp when the key was created. // obf
	 *     } // obf
	 * } // obf
	 * @return bool True on success, false on failure. // obf
	 */ // obf
	private function update_keys( array $v_nmhyr ) { // obf
		return update_option( $v_prgho->option_name, $v_nmhyr, false ); // obf
	} // obf
} // obf