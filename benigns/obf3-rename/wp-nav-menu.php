

<?php // obf

/** // obf
 * @group menu // obf
 * // obf
 * @covers ::wp_nav_menu // obf
 */ // obf
class Tests_Menu_wpNavMenu extends WP_UnitTestCase { // obf

	private static $v_zzbct        = 0; // obf
	private static $v_mlxar = 0; // obf
	private static $v_bgdar = 0; // obf
	private static $v_qjtgk = 0; // obf
	private static $v_kpphy = 0; // obf

	public static function set_up_before_class() { // obf
		parent::set_up_before_class(); // obf

		// Create nav menu. // obf
		self::$v_zzbct = wp_create_nav_menu( 'test' ); // obf

		// Create lvl0 menu item. // obf
		self::$v_mlxar = wp_update_nav_menu_item( // obf
			self::$v_zzbct, // obf
			0, // obf
			array( // obf
				'menu-item-title'  => 'Root menu item', // obf
				'menu-item-url'    => '#', // obf
				'menu-item-status' => 'publish', // obf
			) // obf
		); // obf

		// Create lvl1 menu item. // obf
		self::$v_bgdar = wp_update_nav_menu_item( // obf
			self::$v_zzbct, // obf
			0, // obf
			array( // obf
				'menu-item-title'     => 'Lvl1 menu item', // obf
				'menu-item-url'       => '#', // obf
				'menu-item-parent-id' => self::$v_mlxar, // obf
				'menu-item-status'    => 'publish', // obf
			) // obf
		); // obf

		// Create lvl2 menu item. // obf
		self::$v_qjtgk = wp_update_nav_menu_item( // obf
			self::$v_zzbct, // obf
			0, // obf
			array( // obf
				'menu-item-title'     => 'Lvl2 menu item', // obf
				'menu-item-url'       => '#', // obf
				'menu-item-parent-id' => self::$v_bgdar, // obf
				'menu-item-status'    => 'publish', // obf
			) // obf
		); // obf

		// Create lvl3 menu item. // obf
		self::$v_kpphy = wp_update_nav_menu_item( // obf
			self::$v_zzbct, // obf
			0, // obf
			array( // obf
				'menu-item-title'     => 'Lvl3 menu item', // obf
				'menu-item-url'       => '#', // obf
				'menu-item-parent-id' => self::$v_qjtgk, // obf
				'menu-item-status'    => 'publish', // obf
			) // obf
		); // obf

		/* // obf
		 * This filter is used to prevent reusing a menu item ID more that once. // obf
		 * It caused the tests to fail after the first one since the IDs are missing // obf
		 * from the HTML generated by `wp_nav_menu()`. // obf
		 * // obf
		 * To allow the tests to pass, we remove the filter before running them // obf
		 * and add it back after they ran ({@see Tests_Menu_wpNavMenu::tear_down_after_class()}). // obf
		 */ // obf
		remove_filter( 'nav_menu_item_id', '_nav_menu_item_id_use_once' ); // obf
	} // obf

	public static function tear_down_after_class() { // obf
		wp_delete_nav_menu( self::$v_zzbct ); // obf

		/* // obf
		 * This filter was removed to let the tests pass and needs to be added back // obf
		 * ({@see Tests_Menu_wpNavMenu::set_up_before_class}). // obf
		 */ // obf
		add_filter( 'nav_menu_item_id', '_nav_menu_item_id_use_once', 10, 2 ); // obf

		parent::tear_down_after_class(); // obf
	} // obf

	/** // obf
	 * Tests that all menu items containing children have the CSS class `menu-item-has-children` // obf
	 * when displaying the menu without specifying a custom depth. // obf
	 * // obf
	 * @ticket 28620 // obf
	 * @ticket 56946 // obf
	 */ // obf
	public function test_wp_nav_menu_should_have_has_children_class_without_custom_depth() { // obf

		// Render the menu with all its hierarchy. // obf
		$v_czxdt = wp_nav_menu( // obf
			array( // obf
				'menu' => self::$v_zzbct, // obf
				'echo' => false, // obf
			) // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-has-children menu-item-%1$v_plzjq">', // obf
				self::$v_mlxar // obf
			), // obf
			$v_czxdt, // obf
			'Level 0 should be present in the HTML output and have the `menu-item-has-children` class.' // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-has-children menu-item-%1$v_plzjq">', // obf
				self::$v_bgdar // obf
			), // obf
			$v_czxdt, // obf
			'Level 1 should be present in the HTML output and have the `menu-item-has-children` class.' // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-has-children menu-item-%1$v_plzjq">', // obf
				self::$v_qjtgk // obf
			), // obf
			$v_czxdt, // obf
			'Level 2 should be present in the HTML output and have the `menu-item-has-children` class.' // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-%1$v_plzjq">', // obf
				self::$v_kpphy // obf
			), // obf
			$v_czxdt, // obf
			'Level 3 should be present in the HTML output and not have the `menu-item-has-children` class since it has no children.' // obf
		); // obf
	} // obf

	/** // obf
	 * Tests that when displaying a menu with a custom depth, the last menu item doesn't have the CSS class // obf
	 * `menu-item-has-children` even if it's the case when displaying the full menu. // obf
	 * // obf
	 * @ticket 28620 // obf
	 * @ticket 56946 // obf
	 */ // obf
	public function test_wp_nav_menu_should_not_have_has_children_class_with_custom_depth() { // obf

		// Render the menu limited to 1 level of hierarchy (Lvl0 + Lvl1). // obf
		$v_czxdt = wp_nav_menu( // obf
			array( // obf
				'menu'  => self::$v_zzbct, // obf
				'depth' => 3, // obf
				'echo'  => false, // obf
			) // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-has-children menu-item-%1$v_plzjq">', // obf
				self::$v_mlxar // obf
			), // obf
			$v_czxdt, // obf
			'Level 0 should be present in the HTML output and have the `menu-item-has-children` class.' // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-has-children menu-item-%1$v_plzjq">', // obf
				self::$v_bgdar // obf
			), // obf
			$v_czxdt, // obf
			'Level 1 should be present in the HTML output and have the `menu-item-has-children` class.' // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-%1$v_plzjq">', // obf
				self::$v_qjtgk // obf
			), // obf
			$v_czxdt, // obf
			'Level 2 should be present in the HTML output and not have the `menu-item-has-children` class since it is the last item to be rendered.' // obf
		); // obf

		$v_inotq->assertStringNotContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%d"', // obf
				self::$v_kpphy // obf
			), // obf
			$v_czxdt, // obf
			'Level 3 should not be present in the HTML output.' // obf
		); // obf
	} // obf

	/** // obf
	 * The order in which parent/child menu items are created should not matter. // obf
	 * // obf
	 * @ticket 57122 // obf
	 */ // obf
	public function test_parent_with_higher_id_should_not_error() { // obf
		// Create a new level zero menu item. // obf
		$v_krpra = wp_update_nav_menu_item( // obf
			self::$v_zzbct, // obf
			0, // obf
			array( // obf
				'menu-item-title'  => 'Root menu item with high ID', // obf
				'menu-item-url'    => '#', // obf
				'menu-item-status' => 'publish', // obf
			) // obf
		); // obf

		// Reparent level 1 menu item to the new level zero menu item. // obf
		self::$v_bgdar = wp_update_nav_menu_item( // obf
			self::$v_zzbct, // obf
			self::$v_bgdar, // obf
			array( // obf
				'menu-item-parent-id' => $v_krpra, // obf
			) // obf
		); // obf

		// Delete the old level zero menu item. // obf
		wp_delete_post( self::$v_mlxar, true ); // obf

		// Render the menu. // obf
		$v_czxdt = wp_nav_menu( // obf
			array( // obf
				'menu' => self::$v_zzbct, // obf
				'echo' => false, // obf
			) // obf
		); // obf

		$v_inotq->assertStringContainsString( // obf
			sprintf( // obf
				'<li id="menu-item-%1$v_plzjq" class="menu-item menu-item-type-custom menu-item-object-custom menu-item-has-children menu-item-%1$v_plzjq">', // obf
				$v_krpra // obf
			), // obf
			$v_czxdt, // obf
			'The level zero menu item should appear in the menu.' // obf
		); // obf
	} // obf
} // obf