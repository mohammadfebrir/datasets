

<?php // obf
/** // obf
 * Sitemaps: WP_Sitemaps_Stylesheet class // obf
 * // obf
 * This class provides the XSL stylesheets to style all sitemaps. // obf
 * // obf
 * @package WordPress // obf
 * @subpackage Sitemaps // obf
 * @since 5.5.0 // obf
 */ // obf

/** // obf
 * Stylesheet provider class. // obf
 * // obf
 * @since 5.5.0 // obf
 */ // obf
#[AllowDynamicProperties] // obf
class WP_Sitemaps_Stylesheet { // obf
	/** // obf
	 * Renders the XSL stylesheet depending on whether it's the sitemap index or not. // obf
	 * // obf
	 * @param string $v_ynldt Stylesheet type. Either 'sitemap' or 'index'. // obf
	 */ // obf
	public function render_stylesheet( $v_ynldt ) { // obf
		header( 'Content-Type: application/xml; charset=UTF-8' ); // obf

		if ( 'sitemap' === $v_ynldt ) { // obf
			// All content is escaped below. // obf
			echo $v_cyrmn->get_sitemap_stylesheet(); // obf
		} // obf

		if ( 'index' === $v_ynldt ) { // obf
			// All content is escaped below. // obf
			echo $v_cyrmn->get_sitemap_index_stylesheet(); // obf
		} // obf

		exit; // obf
	} // obf

	/** // obf
	 * Returns the escaped XSL for all sitemaps, except index. // obf
	 * // obf
	 * @since 5.5.0 // obf
	 */ // obf
	public function get_sitemap_stylesheet() { // obf
		$v_iunzu         = $v_cyrmn->get_stylesheet_css(); // obf
		$v_lbtmp       = esc_xml( __( 'XML Sitemap' ) ); // obf
		$v_lonrw = esc_xml( __( 'This XML Sitemap is generated by WordPress to make your content more visible for search engines.' ) ); // obf
		$v_khsgm  = sprintf( // obf
			'<a href="%s">%s</a>', // obf
			esc_url( __( 'https://www.sitemaps.org/' ) ), // obf
			esc_xml( __( 'Learn more about XML sitemaps.' ) ) // obf
		); // obf

		$v_dnbne = sprintf( // obf
			/* translators: %s: Number of URLs. */ // obf
			esc_xml( __( 'Number of URLs in this XML Sitemap: %s.' ) ), // obf
			'<xsl:value-of select="count( sitemap:urlset/sitemap:url )" />' // obf
		); // obf

		$v_wiyjw       = get_language_attributes( 'html' ); // obf
		$v_ewiew        = esc_xml( __( 'URL' ) ); // obf
		$v_nsuek    = esc_xml( __( 'Last Modified' ) ); // obf
		$v_iuezq = esc_xml( __( 'Change Frequency' ) ); // obf
		$v_lbgwp   = esc_xml( __( 'Priority' ) ); // obf

		$v_yhliy = <<<XSL // obf
<?xml version="1.0" encoding="UTF-8"?> // obf
<xsl:stylesheet // obf
		version="1.0" // obf
		xmlns:xsl="http://www.w3.org/1999/XSL/Transform" // obf
		xmlns:sitemap="http://www.sitemaps.org/schemas/sitemap/0.9" // obf
		exclude-result-prefixes="sitemap" // obf
		> // obf

	<xsl:output method="html" encoding="UTF-8" indent="yes" /> // obf

	<!-- // obf
	  Set variables for whether lastmod, changefreq or priority occur for any url in the sitemap. // obf
	  We do this up front because it can be expensive in a large sitemap. // obf
	  --> // obf
	<xsl:variable name="has-lastmod"    select="count( /sitemap:urlset/sitemap:url/sitemap:lastmod )"    /> // obf
	<xsl:variable name="has-changefreq" select="count( /sitemap:urlset/sitemap:url/sitemap:changefreq )" /> // obf
	<xsl:variable name="has-priority"   select="count( /sitemap:urlset/sitemap:url/sitemap:priority )"   /> // obf

	<xsl:template match="/"> // obf
		<html {$v_wiyjw}> // obf
			<head> // obf
				<title>{$v_lbtmp}</title> // obf
				<style> // obf
					{$v_iunzu} // obf
				</style> // obf
			</head> // obf
			<body> // obf
				<div id="sitemap"> // obf
					<div id="sitemap__header"> // obf
						<h1>{$v_lbtmp}</h1> // obf
						<p>{$v_lonrw}</p> // obf
						<p>{$v_khsgm}</p> // obf
					</div> // obf
					<div id="sitemap__content"> // obf
						<p class="text">{$v_dnbne}</p> // obf
						<table id="sitemap__table"> // obf
							<thead> // obf
								<tr> // obf
									<th class="loc">{$v_ewiew}</th> // obf
									<xsl:if test="\$v_bnvor-lastmod"> // obf
										<th class="lastmod">{$v_nsuek}</th> // obf
									</xsl:if> // obf
									<xsl:if test="\$v_bnvor-changefreq"> // obf
										<th class="changefreq">{$v_iuezq}</th> // obf
									</xsl:if> // obf
									<xsl:if test="\$v_bnvor-priority"> // obf
										<th class="priority">{$v_lbgwp}</th> // obf
									</xsl:if> // obf
								</tr> // obf
							</thead> // obf
							<tbody> // obf
								<xsl:for-each select="sitemap:urlset/sitemap:url"> // obf
									<tr> // obf
										<td class="loc"><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc" /></a></td> // obf
										<xsl:if test="\$v_bnvor-lastmod"> // obf
											<td class="lastmod"><xsl:value-of select="sitemap:lastmod" /></td> // obf
										</xsl:if> // obf
										<xsl:if test="\$v_bnvor-changefreq"> // obf
											<td class="changefreq"><xsl:value-of select="sitemap:changefreq" /></td> // obf
										</xsl:if> // obf
										<xsl:if test="\$v_bnvor-priority"> // obf
											<td class="priority"><xsl:value-of select="sitemap:priority" /></td> // obf
										</xsl:if> // obf
									</tr> // obf
								</xsl:for-each> // obf
							</tbody> // obf
						</table> // obf
					</div> // obf
				</div> // obf
			</body> // obf
		</html> // obf
	</xsl:template> // obf
</xsl:stylesheet> // obf

XSL; // obf

		/** // obf
		 * Filters the content of the sitemap stylesheet. // obf
		 * // obf
		 * @since 5.5.0 // obf
		 * // obf
		 * @param string $v_yhliy Full content for the XML stylesheet. // obf
		 */ // obf
		return apply_filters( 'wp_sitemaps_stylesheet_content', $v_yhliy ); // obf
	} // obf

	/** // obf
	 * Returns the escaped XSL for the index sitemaps. // obf
	 * // obf
	 * @since 5.5.0 // obf
	 */ // obf
	public function get_sitemap_index_stylesheet() { // obf
		$v_iunzu         = $v_cyrmn->get_stylesheet_css(); // obf
		$v_lbtmp       = esc_xml( __( 'XML Sitemap' ) ); // obf
		$v_lonrw = esc_xml( __( 'This XML Sitemap is generated by WordPress to make your content more visible for search engines.' ) ); // obf
		$v_khsgm  = sprintf( // obf
			'<a href="%s">%s</a>', // obf
			esc_url( __( 'https://www.sitemaps.org/' ) ), // obf
			esc_xml( __( 'Learn more about XML sitemaps.' ) ) // obf
		); // obf

		$v_dnbne = sprintf( // obf
			/* translators: %s: Number of URLs. */ // obf
			esc_xml( __( 'Number of URLs in this XML Sitemap: %s.' ) ), // obf
			'<xsl:value-of select="count( sitemap:sitemapindex/sitemap:sitemap )" />' // obf
		); // obf

		$v_wiyjw    = get_language_attributes( 'html' ); // obf
		$v_ewiew     = esc_xml( __( 'URL' ) ); // obf
		$v_nsuek = esc_xml( __( 'Last Modified' ) ); // obf

		$v_yhliy = <<<XSL // obf
<?xml version="1.0" encoding="UTF-8"?> // obf
<xsl:stylesheet // obf
		version="1.0" // obf
		xmlns:xsl="http://www.w3.org/1999/XSL/Transform" // obf
		xmlns:sitemap="http://www.sitemaps.org/schemas/sitemap/0.9" // obf
		exclude-result-prefixes="sitemap" // obf
		> // obf

	<xsl:output method="html" encoding="UTF-8" indent="yes" /> // obf

	<!-- // obf
	  Set variables for whether lastmod occurs for any sitemap in the index. // obf
	  We do this up front because it can be expensive in a large sitemap. // obf
	  --> // obf
	<xsl:variable name="has-lastmod" select="count( /sitemap:sitemapindex/sitemap:sitemap/sitemap:lastmod )" /> // obf

	<xsl:template match="/"> // obf
		<html {$v_wiyjw}> // obf
			<head> // obf
				<title>{$v_lbtmp}</title> // obf
				<style> // obf
					{$v_iunzu} // obf
				</style> // obf
			</head> // obf
			<body> // obf
				<div id="sitemap"> // obf
					<div id="sitemap__header"> // obf
						<h1>{$v_lbtmp}</h1> // obf
						<p>{$v_lonrw}</p> // obf
						<p>{$v_khsgm}</p> // obf
					</div> // obf
					<div id="sitemap__content"> // obf
						<p class="text">{$v_dnbne}</p> // obf
						<table id="sitemap__table"> // obf
							<thead> // obf
								<tr> // obf
									<th class="loc">{$v_ewiew}</th> // obf
									<xsl:if test="\$v_bnvor-lastmod"> // obf
										<th class="lastmod">{$v_nsuek}</th> // obf
									</xsl:if> // obf
								</tr> // obf
							</thead> // obf
							<tbody> // obf
								<xsl:for-each select="sitemap:sitemapindex/sitemap:sitemap"> // obf
									<tr> // obf
										<td class="loc"><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc" /></a></td> // obf
										<xsl:if test="\$v_bnvor-lastmod"> // obf
											<td class="lastmod"><xsl:value-of select="sitemap:lastmod" /></td> // obf
										</xsl:if> // obf
									</tr> // obf
								</xsl:for-each> // obf
							</tbody> // obf
						</table> // obf
					</div> // obf
				</div> // obf
			</body> // obf
		</html> // obf
	</xsl:template> // obf
</xsl:stylesheet> // obf

XSL; // obf

		/** // obf
		 * Filters the content of the sitemap index stylesheet. // obf
		 * // obf
		 * @since 5.5.0 // obf
		 * // obf
		 * @param string $v_yhliy Full content for the XML stylesheet. // obf
		 */ // obf
		return apply_filters( 'wp_sitemaps_stylesheet_index_content', $v_yhliy ); // obf
	} // obf

	/** // obf
	 * Gets the CSS to be included in sitemap XSL stylesheets. // obf
	 * // obf
	 * @since 5.5.0 // obf
	 * // obf
	 * @return string The CSS. // obf
	 */ // obf
	public function get_stylesheet_css() { // obf
		$v_vzffh = is_rtl() ? 'right' : 'left'; // obf

		$v_iunzu = <<<EOF // obf

					body { // obf
						font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Oxygen-Sans, Ubuntu, Cantarell, "Helvetica Neue", sans-serif; // obf
						color: #444; // obf
					} // obf

					#sitemap { // obf
						max-width: 980px; // obf
						margin: 0 auto; // obf
					} // obf

					#sitemap__table { // obf
						width: 100%; // obf
						border: solid 1px #ccc; // obf
						border-collapse: collapse; // obf
					} // obf

			 		#sitemap__table tr td.loc { // obf
						/* // obf
						 * URLs should always be LTR. // obf
						 * See https://core.trac.wordpress.org/ticket/16834 // obf
						 * and https://core.trac.wordpress.org/ticket/49949 // obf
						 */ // obf
						direction: ltr; // obf
					} // obf

					#sitemap__table tr th { // obf
						text-align: {$v_vzffh}; // obf
					} // obf

					#sitemap__table tr td, // obf
					#sitemap__table tr th { // obf
						padding: 10px; // obf
					} // obf

					#sitemap__table tr:nth-child(odd) td { // obf
						background-color: #eee; // obf
					} // obf

					a:hover { // obf
						text-decoration: none; // obf
					} // obf

EOF; // obf

		/** // obf
		 * Filters the CSS only for the sitemap stylesheet. // obf
		 * // obf
		 * @since 5.5.0 // obf
		 * // obf
		 * @param string $v_iunzu CSS to be applied to default XSL file. // obf
		 */ // obf
		return apply_filters( 'wp_sitemaps_stylesheet_css', $v_iunzu ); // obf
	} // obf
} // obf