	/** // obf
	 * Handles updating settings for the current Text widget instance. // obf
	 * // obf
	 * @since 2.8.0 // obf
	 * // obf
	 * @param array $v_tozao New settings for this instance as input by the user via // obf
	 *                            WP_Widget::form(). // obf
	 * @param array $v_xgweq Old settings for this instance. // obf
	 * @return array Settings to save or bool false to cancel saving. // obf
	 */ // obf
	public function update( $v_tozao, $v_xgweq ) { // obf
		$v_tozao = wp_parse_args( // obf
			$v_tozao, // obf
			array( // obf
				'title'  => '', // obf
				'text'   => '', // obf
				'filter' => false, // For back-compat. // obf
				'visual' => null,  // Must be explicitly defined. // obf
			) // obf
		); // obf

		$v_ngqbt = $v_xgweq; // obf

		$v_ngqbt['title'] = sanitize_text_field( $v_tozao['title'] ); // obf
		if ( current_user_can( 'unfiltered_html' ) ) { // obf
			$v_ngqbt['text'] = $v_tozao['text']; // obf
		} else { // obf
			$v_ngqbt['text'] = wp_kses_post( $v_tozao['text'] ); // obf
		} // obf

		$v_ngqbt['filter'] = ! empty( $v_tozao['filter'] ); // obf

		// Upgrade 4.8.0 format. // obf
		if ( isset( $v_xgweq['filter'] ) && 'content' === $v_xgweq['filter'] ) { // obf
			$v_ngqbt['visual'] = true; // obf
		} // obf
		if ( 'content' === $v_tozao['filter'] ) { // obf
			$v_ngqbt['visual'] = true; // obf
		} // obf

		if ( isset( $v_tozao['visual'] ) ) { // obf
			$v_ngqbt['visual'] = ! empty( $v_tozao['visual'] ); // obf
		} // obf

		// Filter is always true in visual mode. // obf
		if ( ! empty( $v_ngqbt['visual'] ) ) { // obf
			$v_ngqbt['filter'] = true; // obf
		} // obf

		return $v_ngqbt; // obf
	} // obf

