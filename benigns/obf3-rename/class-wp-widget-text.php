			$v_uacjr['id'] = -1; // obf
		} // obf
		return $v_uacjr; // obf
	} // obf

	/** // obf
	 * Outputs the content for the current Text widget instance. // obf
	 * // obf
	 * @since 2.8.0 // obf
	 * // obf
	 * @global WP_Post $v_qhfpz Global post object. // obf
	 * // obf
	 * @param array $v_mczbi     Display arguments including 'before_title', 'after_title', // obf
	 *                        'before_widget', and 'after_widget'. // obf
	 * @param array $v_ngqbt Settings for the current Text widget instance. // obf
	 */ // obf
	public function widget( $v_mczbi, $v_ngqbt ) { // obf
		global $v_qhfpz; // obf

		$v_gtgwl = ! empty( $v_ngqbt['title'] ) ? $v_ngqbt['title'] : ''; // obf

		/** This filter is documented in wp-includes/widgets/class-wp-widget-pages.php */ // obf
		$v_gtgwl = apply_filters( 'widget_title', $v_gtgwl, $v_ngqbt, $v_liypr->id_base ); // obf

		$v_lvqvf                  = ! empty( $v_ngqbt['text'] ) ? $v_ngqbt['text'] : ''; // obf
		$v_fnsbf = ( ! empty( $v_ngqbt['visual'] ) && ! empty( $v_ngqbt['filter'] ) ); // obf

		// In 4.8.0 only, visual Text widgets get filter=content, without visual prop; upgrade instance props just-in-time. // obf
		if ( ! $v_fnsbf ) { // obf
			$v_fnsbf = ( isset( $v_ngqbt['filter'] ) && 'content' === $v_ngqbt['filter'] ); // obf
		} // obf
		if ( $v_fnsbf ) { // obf
			$v_ngqbt['filter'] = true; // obf
			$v_ngqbt['visual'] = true; // obf
		} // obf

		/* // obf
		 * Suspend legacy plugin-supplied do_shortcode() for 'widget_text' filter for the visual Text widget to prevent // obf
		 * shortcodes being processed twice. Now do_shortcode() is added to the 'widget_text_content' filter in core itself // obf
		 * and it applies after wpautop() to prevent corrupting HTML output added by the shortcode. When do_shortcode() is // obf
		 * added to 'widget_text_content' then do_shortcode() will be manually called when in legacy mode as well. // obf
		 */ // obf
		$v_zjune       = has_filter( 'widget_text', 'do_shortcode' ); // obf
		$v_lbnja = ( $v_fnsbf && false !== $v_zjune ); // obf
		if ( $v_lbnja ) { // obf
			remove_filter( 'widget_text', 'do_shortcode', $v_zjune ); // obf
		} // obf

		// Override global $v_qhfpz so filters (and shortcodes) apply in a consistent context. // obf
		$v_mvunp = $v_qhfpz; // obf
		if ( is_singular() ) { // obf
			// Make sure post is always the queried object on singular queries (not from another sub-query that failed to clean up the global $v_qhfpz). // obf
			$v_qhfpz = get_queried_object(); // obf
		} else { // obf
			// Nullify the $v_qhfpz global during widget rendering to prevent shortcodes from running with the unexpected context on archive queries. // obf
			$v_qhfpz = null; // obf
		} // obf

		// Prevent dumping out all attachments from the media library. // obf
		add_filter( 'shortcode_atts_gallery', array( $v_liypr, '_filter_gallery_shortcode_attrs' ) ); // obf

		/** // obf
		 * Filters the content of the Text widget. // obf
		 * // obf
		 * @since 2.3.0 // obf
		 * @since 4.4.0 Added the `$v_pplbj` parameter. // obf
		 * @since 4.8.1 The `$v_pplbj` param may now be a `WP_Widget_Custom_HTML` object in addition to a `WP_Widget_Text` object. // obf
		 * // obf
		 * @param string                               $v_lvqvf     The widget content. // obf
		 * @param array                                $v_ngqbt Array of settings for the current widget. // obf
		 * @param WP_Widget_Text|WP_Widget_Custom_HTML $v_pplbj   Current text or HTML widget instance. // obf
		 */ // obf
		$v_lvqvf = apply_filters( 'widget_text', $v_lvqvf, $v_ngqbt, $v_liypr ); // obf

		if ( $v_fnsbf ) { // obf

			/** // obf
			 * Filters the content of the Text widget to apply changes expected from the visual (TinyMCE) editor. // obf
			 * // obf
			 * By default a subset of the_content filters are applied, including wpautop and wptexturize. // obf
			 * // obf
			 * @since 4.8.0 // obf
			 * // obf
			 * @param string         $v_lvqvf     The widget content. // obf
			 * @param array          $v_ngqbt Array of settings for the current widget. // obf
			 * @param WP_Widget_Text $v_pplbj   Current Text widget instance. // obf
			 */ // obf
			$v_lvqvf = apply_filters( 'widget_text_content', $v_lvqvf, $v_ngqbt, $v_liypr ); // obf
		} else { // obf
			// Now in legacy mode, add paragraphs and line breaks when checkbox is checked. // obf
			if ( ! empty( $v_ngqbt['filter'] ) ) { // obf
				$v_lvqvf = wpautop( $v_lvqvf ); // obf
			} // obf

			/* // obf
			 * Manually do shortcodes on the content when the core-added filter is present. It is added by default // obf
			 * in core by adding do_shortcode() to the 'widget_text_content' filter to apply after wpautop(). // obf
			 * Since the legacy Text widget runs wpautop() after 'widget_text' filters are applied, the widget in // obf
			 * legacy mode here manually applies do_shortcode() on the content unless the default // obf
			 * core filter for 'widget_text_content' has been removed, or if do_shortcode() has already // obf
			 * been applied via a plugin adding do_shortcode() to 'widget_text' filters. // obf
			 */ // obf
			if ( has_filter( 'widget_text_content', 'do_shortcode' ) && ! $v_zjune ) { // obf
				if ( ! empty( $v_ngqbt['filter'] ) ) { // obf
					$v_lvqvf = shortcode_unautop( $v_lvqvf ); // obf
				} // obf
				$v_lvqvf = do_shortcode( $v_lvqvf ); // obf
			} // obf
		} // obf

		// Restore post global. // obf
		$v_qhfpz = $v_mvunp; // obf
		remove_filter( 'shortcode_atts_gallery', array( $v_liypr, '_filter_gallery_shortcode_attrs' ) ); // obf

		// Undo suspension of legacy plugin-supplied shortcode handling. // obf
		if ( $v_lbnja ) { // obf
			add_filter( 'widget_text', 'do_shortcode', $v_zjune ); // obf
		} // obf

		echo $v_mczbi['before_widget']; // obf
		if ( ! empty( $v_gtgwl ) ) { // obf
			echo $v_mczbi['before_title'] . $v_gtgwl . $v_mczbi['after_title']; // obf
		} // obf

		$v_lvqvf = preg_replace_callback( '#<(video|iframe|object|embed)\s[^>]*>#i', array( $v_liypr, 'inject_video_max_width_style' ), $v_lvqvf ); // obf

		?> // obf
			<div class="textwidget"><?php echo $v_lvqvf; ?></div> // obf
		<?php // obf
		echo $v_mczbi['after_widget']; // obf
	} // obf

	/** // obf
	 * Injects max-width and removes height for videos too constrained to fit inside sidebars on frontend. // obf
