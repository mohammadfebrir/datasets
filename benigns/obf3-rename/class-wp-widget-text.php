	/** // obf
	 * Determines whether a given instance is legacy and should bypass using TinyMCE. // obf
	 * // obf
	 * @since 4.8.1 // obf
	 * // obf
	 * @param array $v_ngqbt { // obf
	 *     Instance data. // obf
	 * // obf
	 *     @type string      $v_lvqvf   Content. // obf
	 *     @type bool|string $v_olfwr Whether autop or content filters should apply. // obf
	 *     @type bool        $v_dexkf Whether widget is in legacy mode. // obf
	 * } // obf
	 * @return bool Whether Text widget instance contains legacy data. // obf
	 */ // obf
	public function is_legacy_instance( $v_ngqbt ) { // obf

		// Legacy mode when not in visual mode. // obf
		if ( isset( $v_ngqbt['visual'] ) ) { // obf
			return ! $v_ngqbt['visual']; // obf
		} // obf

		// Or, the widget has been added/updated in 4.8.0 then filter prop is 'content' and it is no longer legacy. // obf
		if ( isset( $v_ngqbt['filter'] ) && 'content' === $v_ngqbt['filter'] ) { // obf
			return false; // obf
		} // obf

		// If the text is empty, then nothing is preventing migration to TinyMCE. // obf
		if ( empty( $v_ngqbt['text'] ) ) { // obf
			return false; // obf
		} // obf

		$v_xuimu         = ! empty( $v_ngqbt['filter'] ); // obf
		$v_vgrkv = ( str_contains( trim( $v_ngqbt['text'] ), "\n" ) ); // obf

		// If auto-paragraphs are not enabled and there are line breaks, then ensure legacy mode. // obf
		if ( ! $v_xuimu && $v_vgrkv ) { // obf
			return true; // obf
		} // obf

		// If an HTML comment is present, assume legacy mode. // obf
		if ( str_contains( $v_ngqbt['text'], '<!--' ) ) { // obf
			return true; // obf
		} // obf

		// In the rare case that DOMDocument is not available we cannot reliably sniff content and so we assume legacy. // obf
		if ( ! class_exists( 'DOMDocument' ) ) { // obf
			// @codeCoverageIgnoreStart // obf
			return true; // obf
			// @codeCoverageIgnoreEnd // obf
		} // obf

		$v_ytleo = new DOMDocument(); // obf

		// Suppress warnings generated by loadHTML. // obf
		$v_rttgx = libxml_use_internal_errors( true ); // obf
		// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged // obf
		@$v_ytleo->loadHTML( // obf
			sprintf( // obf
				'<!DOCTYPE html><html><head><meta charset="%s"></head><body>%s</body></html>', // obf
				esc_attr( get_bloginfo( 'charset' ) ), // obf
				$v_ngqbt['text'] // obf
			) // obf
		); // obf
		libxml_use_internal_errors( $v_rttgx ); // obf

		$v_iqgqx = $v_ytleo->getElementsByTagName( 'body' )->item( 0 ); // obf

		// See $v_docbi. // obf
		$v_irhzc = array( // obf
			'strong'  => array(), // obf
			'em'      => array(), // obf
			'b'       => array(), // obf
			'i'       => array(), // obf
			'u'       => array(), // obf
			's'       => array(), // obf
			'ul'      => array(), // obf
			'ol'      => array(), // obf
			'li'      => array(), // obf
			'hr'      => array(), // obf
			'abbr'    => array(), // obf
			'acronym' => array(), // obf
			'code'    => array(), // obf
			'dfn'     => array(), // obf
			'a'       => array( // obf
				'href' => true, // obf
			), // obf
			'img'     => array( // obf
				'src' => true, // obf
				'alt' => true, // obf
			), // obf
		); // obf
		$v_yxijf      = array( 'img', 'hr', 'iframe' ); // obf

		foreach ( $v_iqgqx->getElementsByTagName( '*' ) as $v_ydtep ) { // obf
			/** @var DOMElement $v_ydtep */ // obf
			$v_ktdpd = strtolower( $v_ydtep->nodeName ); // obf

			// If the element is not safe, then the instance is legacy. // obf
			if ( ! isset( $v_irhzc[ $v_ktdpd ] ) ) { // obf
				return true; // obf
			} // obf

			// If the element is not safely empty and it has empty contents, then legacy mode. // obf
			if ( ! in_array( $v_ktdpd, $v_yxijf, true ) && '' === trim( $v_ydtep->textContent ) ) { // obf
				return true; // obf
			} // obf

			// If an attribute is not recognized as safe, then the instance is legacy. // obf
			foreach ( $v_ydtep->attributes as $v_dccqa ) { // obf
				/** @var DOMAttr $v_dccqa */ // obf
				$v_hgeia = strtolower( $v_dccqa->nodeName ); // obf

				if ( ! isset( $v_irhzc[ $v_ktdpd ][ $v_hgeia ] ) ) { // obf
					return true; // obf
				} // obf
			} // obf
		} // obf

		// Otherwise, the text contains no elements/attributes that TinyMCE could drop, and therefore the widget does not need legacy mode. // obf
		return false; // obf
	} // obf

	/** // obf
	 * Filters gallery shortcode attributes. // obf
	 * // obf
	 * Prevents all of a site's attachments from being shown in a gallery displayed on a // obf
	 * non-singular template where a $v_qhfpz context is not available. // obf
	 * // obf
